/** The label for a key. Falls back to the key itself so a typo is visible. */
export function T(key) {
  const value = DICT[key];
  return value === undefined ? key : value;
}

/**
 * The same label, escaped for interpolation into HTML. Screens build markup as
 * strings, so this is the form to reach for anywhere a label lands inside an
 * `html:` property rather than a text node.
 */
export function L(key) {
  return esc(T(key));
}

export function esc(s) {
  return String(s ?? '').replace(/[&<>"']/g, (c) => ({
    '&': '&amp;',
    '<': '&lt;',
    '>': '&gt;',
    '"': '&quot;',
    "'": '&#39;',
  })[c]);
}
